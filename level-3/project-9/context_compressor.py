def synthesize_answer(query: str, context_text: str, model_name: str = model_used) -> str:
    """Generates the final answer strictly grounded in the provided context."""
    client = genai.Client()
    prompt = f"""Context Information:
\"\"\"
{context_text}
\"\"\"

User Question: {query}

Instructions: Answer the question using ONLY the facts from the context above. Be concise and precise."""

    response = client.models.generate_content(
        model=model_name,
        contents=prompt,
        config=types.GenerateContentConfig(
            temperature=0.0
        ),
    )
    return response.text.strip() if response.text else ""

