enc = tiktoken.get_encoding("cl100k_base")

model_used = "gemini-3.6-flash"

class ContextCompressor:
    def __init__(self, model_name: str = model_used):
        # Automatically loads GEMINI_API_KEY from environment
        self.client = genai.Client()
        self.model_name = model_name

    def compress_chunk(self, query: str, chunk: Dict[str, str]) -> str:
        """
        Extracts only the critical factual sentences from a chunk that directly 
        relate to the query. Returns an empty string if irrelevant.
        """
        system_instruction = (
            "You are a strict context compression engine. Your job is to extract ONLY the exact, "
            "verbatim factual sentences or clauses from the provided text that are directly needed "
            "to answer the user's query.\n"
            "- Do NOT paraphrase or add explanations.\n"
            "- Strip all conversational filler, preambles, and unrelated technical details.\n"
            "- If the chunk contains NO relevant information to answer the query, output strictly NOTHING (empty string)."
        )

        prompt = f"""Target Query: {query}

Source Chunk Title: {chunk['title']}
Source Chunk Content:
\"\"\"{chunk['content']}\"\"\"

Extracted Relevant Snippet:"""

        response = self.client.models.generate_content(
            model=self.model_name,
            contents=prompt,
            config=types.GenerateContentConfig(
                system_instruction=system_instruction,
                temperature=0.0, # Deterministic extraction
            ),
        )
        
        if response.text:
            return response.text.strip()
        return ""

    def compress_all(self, query: str, chunks: List[Dict[str, str]]) -> List[Dict[str, str]]:
        compressed_results = []
        for chunk in chunks:
            extracted_snippet = self.compress_chunk(query, chunk)
            if extracted_snippet:  # Discard chunks that compressed to empty
                compressed_results.append({
                    "chunk_id": chunk["chunk_id"],
                    "title": chunk["title"],
                    "extracted_content": extracted_snippet
                })
        return compressed_results


def count_token(text: str) -> int:
    return len(enc.encode(text))

